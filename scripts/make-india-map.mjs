// Builds the tracking map's data from public sources (run once; the outputs are committed):
//   lib/geo/india-outline.ts  India's outline as one SVG path, from Natural Earth's India
//                             point-of-view boundaries (public domain), which show Jammu & Kashmir
//                             and Ladakh as India officially depicts them.
//   lib/geo/india-places.json Towns (population 1,000+), district seats and districts with their
//                             coordinates, from GeoNames (CC BY 4.0, credited under the map).
//
// Usage: node scripts/make-india-map.mjs <ne_10m_admin_0_countries_ind.geojson> <GeoNames IN.txt> <admin1CodesASCII.txt>
//   https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_countries_ind.geojson
//   https://download.geonames.org/export/dump/IN.zip (unzip → IN.txt)
//   https://download.geonames.org/export/dump/admin1CodesASCII.txt
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createInterface } from 'node:readline';
import { createReadStream } from 'node:fs';
import { project, BOUNDS } from '../lib/geo/project.ts';
import { placeKey, stateKey } from '../lib/geo/place-key.ts';

const [neFile, geonamesFile, admin1File] = process.argv.slice(2);
if (!neFile || !geonamesFile || !admin1File) {
  console.error('Usage: node scripts/make-india-map.mjs <ne geojson> <IN.txt> <admin1CodesASCII.txt>');
  process.exit(1);
}
mkdirSync('lib/geo', { recursive: true });

// ---------- Outline ----------

/** Douglas–Peucker on projected points. */
function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = points[a];
    const [bx, by] = points[b];
    const dx = bx - ax;
    const dy = by - ay;
    const len = Math.hypot(dx, dy) || 1;
    let worst = -1;
    let at = -1;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * points[i][0] - dx * points[i][1] + bx * ay - by * ax) / len;
      if (d > worst) {
        worst = d;
        at = i;
      }
    }
    if (worst > tolerance) {
      keep[at] = 1;
      stack.push([a, at], [at, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

const area = (ring) => {
  let s = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) s += (ring[j][0] + ring[i][0]) * (ring[j][1] - ring[i][1]);
  return Math.abs(s / 2);
};

const ne = JSON.parse(readFileSync(neFile, 'utf8'));
const india = ne.features.find((f) => f.properties.ADM0_A3 === 'IND');
const polygons = india.geometry.type === 'Polygon' ? [india.geometry.coordinates] : india.geometry.coordinates;
let d = '';
let kept = 0;
for (const poly of polygons) {
  const ring = poly[0].map(([lon, lat]) => {
    const p = project(lat, lon);
    return [p.x, p.y];
  });
  if (area(ring) < 0.02) continue; // only specks; keeps Lakshadweep and the smaller Andaman and Nicobar islands
  // A ring starts and ends on the same point, so it is simplified as two open halves.
  const mid = Math.floor(ring.length / 2);
  const s = [...simplify(ring.slice(0, mid + 1), 0.35).slice(0, -1), ...simplify(ring.slice(mid), 0.35)];
  if (s.length < 4) continue;
  kept++;
  d += 'M' + s.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L') + 'Z';
}
writeFileSync(
  'lib/geo/india-outline.ts',
  `// GENERATED by scripts/make-india-map.mjs from Natural Earth's India point-of-view boundaries
// (ne_10m_admin_0_countries_ind, public domain). Do not edit by hand.
/** India's outline in the map's coordinates (lib/geo/project.ts). ${kept} shapes. */
export const INDIA_OUTLINE = '${d}';
`,
);
console.log('outline:', kept, 'shapes,', d.length, 'characters');

// ---------- Places ----------

const states = new Map(); // "IN.19" → state name
for (const line of readFileSync(admin1File, 'utf8').split('\n')) {
  const [code, name] = line.split('\t');
  if (code?.startsWith('IN.')) states.set(code.slice(3), name);
}
const stateNames = [...new Set(states.values())].sort();
const stateIndex = new Map(stateNames.map((n, i) => [n, i]));

const places = []; // [name, state index, lat, lon, rank, other spellings (keys)]
const rl = createInterface({ input: createReadStream(geonamesFile, 'utf8'), crlfDelay: Infinity });
for await (const line of rl) {
  const c = line.split('\t');
  const [, name, ascii, alternates, lat, lon, fclass, fcode, , , admin1] = c;
  const pop = Number(c[14]) || 0;
  const state = states.get(admin1);
  if (!state) continue;
  const isSeat = /^PPL(A|A2|A3|C)$/.test(fcode);
  const isDistrict = fclass === 'A' && fcode === 'ADM2';
  if (!(fclass === 'P' && (pop >= 1000 || isSeat)) && !isDistrict) continue;
  const display = (ascii || name).replace(/ District$/, '');
  // Towns outrank districts of the same name (the town is where the hub is).
  const rank = isDistrict ? 1 : Math.round(20 + Math.log10(pop + 10) * 10 + (isSeat ? 10 : 0));
  const keys = new Set();
  if (placeKey(name) !== placeKey(display)) keys.add(placeKey(name));
  // Older and other spellings for larger towns: Bangalore, Mangalore, Bombay, Calicut …
  if (pop >= 50_000 && alternates) {
    for (const alt of alternates.split(',')) if (/^[A-Za-z][A-Za-z .'-]{2,30}$/.test(alt)) keys.add(placeKey(alt));
  }
  keys.delete(placeKey(display));
  const entry = [display, stateIndex.get(state), Number(Number(lat).toFixed(3)), Number(Number(lon).toFixed(3)), rank];
  if (keys.size) entry.push([...keys]);
  places.push(entry);
}
places.sort((a, b) => a[1] - b[1] || b[4] - a[4]);

writeFileSync(
  'lib/geo/india-places.json',
  JSON.stringify({
    source: 'GeoNames (geonames.org), CC BY 4.0',
    states: stateNames,
    stateKeys: stateNames.map(stateKey),
    places,
  }),
);
console.log('places:', places.length, 'entries,', stateNames.length, 'states/UTs; bounds', BOUNDS);
